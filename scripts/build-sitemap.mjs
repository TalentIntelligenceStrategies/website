/**
 * Write sitemap.xml from the list below. lastmod is each page's last git commit date,
 * or today when the file has uncommitted changes, so it cannot drift the way the
 * hand-kept file did (2026-10-11 audit, LINK-07).
 *
 * Left out on purpose: redirect stubs, /ausa/ (unlisted QR landing page), the two
 * sealed Licensing Platform pages (noindex), 404.html, /legal/ (read in a dialog),
 * and /documents/ + /designs/ (disallowed in robots.txt).
 *
 * Run: node scripts/build-sitemap.mjs   (or `npm run build`)
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const PAGES = [
  ['/', 'index.html', '1.0'],
  ['/sustain/', 'sustain/index.html', '0.9'],
  ['/protect/', 'protect/index.html', '0.9'],
  ['/license/', 'license/index.html', '0.9'],
  ['/ecosystem/', 'ecosystem/index.html', '0.8'],
  ['/why-taiwan/', 'why-taiwan/index.html', '0.8'],
  ['/about/', 'about/index.html', '0.7'],
  ['/product/signal/', 'product/signal/index.html', '0.6'],
];

const git = (...args) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim();
const today = new Date().toLocaleDateString('en-CA', { timeZone: 'Asia/Taipei' });
const lastmod = (file) => (git('status', '--porcelain', '--', file) ? today : git('log', '-1', '--format=%cs', '--', file) || today);

const urls = PAGES.map(([loc, file, pri]) => `  <url>
    <loc>https://tisglobalinc.com${loc}</loc>
    <lastmod>${lastmod(file)}</lastmod>
    <priority>${pri}</priority>
  </url>`).join('\n');

writeFileSync(join(ROOT, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/build-sitemap.mjs. Edit the page list there, not this file. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`);
console.log(`sitemap: ${PAGES.length} urls`);
